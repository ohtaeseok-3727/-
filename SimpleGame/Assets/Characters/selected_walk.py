"""Connect the accepted walking atlas without changing attack clips or image pixels."""
import json
from pathlib import Path


class SelectedWalk:
    def __init__(self, root):
        self.root = Path(root)
        self.directory = self.root / 'Walk/Selected-v3'
        self.manifest = json.loads((self.directory / 'frames.json').read_text(encoding='utf-8'))

    def apply(self, assets, clips):
        index = len(assets)
        assets.append(dict(path='Walk/Selected-v3/walk.png',
                           width=self.manifest['size'][0], height=self.manifest['size'][1]))
        for clip in clips:
            if clip['id'] not in ('knight-walk', 'mage-walk'):
                continue
            row = 0 if clip['id'] == 'knight-walk' else 1
            frames = self.manifest['frames'][row]
            scale = 150.0 / self.manifest['reference_heights'][row]
            # Retain the eight original timing slots: hold each of four poses twice.
            for slot, body in enumerate(clip['body']):
                frame = frames[slot * 4 // len(clip['body'])]
                px, py = frame['pivot']
                body['sprite'] = dict(asset=index, rect=frame['rect'],
                                      offset=[-px * scale, -py * scale], scale=scale, blend=0)
        self.write_header()

    def write_header(self):
        lines = ['#pragma once', '// Generated by Assets/Characters/selected_walk.py.',
                 'namespace SelectedWalk {',
                 'struct Frame { int x,y,w,h; float pivotX,pivotY; };',
                 'static constexpr wchar_t path[] = L"Walk/Selected-v3/walk.png";',
                 f'static constexpr int width = {self.manifest["size"][0]};',
                 f'static constexpr int height = {self.manifest["size"][1]};',
                 'static constexpr Frame frames[3][4] = {']
        for row in self.manifest['frames']:
            lines.append('{')
            for frame in row:
                rect = ','.join(map(str, frame['rect']))
                px, py = frame['pivot']
                lines.append('{%s,%.6ff,%.6ff},' % (rect, px, py))
            lines.append('},')
        lines += ['};', 'static constexpr float referenceHeights[] = {' +
                  ','.join('%.6ff' % n for n in self.manifest['reference_heights']) + '};',
                  'static constexpr float knightHilts[4][2] = {']
        for frame, point in zip(self.manifest['frames'][0], self.manifest['knight_hilts']):
            lines.append('{%.6ff,%.6ff},' % (point[0] - frame['rect'][0],
                                           point[1] - frame['rect'][1]))
        lines += ['};', '}']
        target = self.root.parents[1] / 'src/generated/SelectedWalkData.h'
        target.write_text('\n'.join(lines) + '\n', encoding='utf-8')
