"""Read PNG alpha/pivots and generate C03 atlas metadata without modifying images."""

import hashlib
import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "SimpleGame/Assets/Chapter3/StateSheets-v2"
PEOPLE = (("elian", 3), ("edric", 3), ("courier", 3), ("guard", 4), ("serad", 5), ("hero", 4))


def read_png(path):
    raw = path.read_bytes()
    assert raw[:8] == b"\x89PNG\r\n\x1a\n", path
    pos, compressed = 8, bytearray()
    while pos < len(raw):
        size = struct.unpack_from(">I", raw, pos)[0]
        kind, data = raw[pos + 4:pos + 8], raw[pos + 8:pos + 8 + size]
        if kind == b"IHDR":
            width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", data)
            assert depth == 8 and color == 6 and interlace == 0, (path, depth, color, interlace)
        elif kind == b"IDAT":
            compressed.extend(data)
        pos += size + 12
    filtered = zlib.decompress(compressed)
    stride, rows = width * 4, []
    previous = bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        mode = filtered[start]
        row = bytearray(filtered[start + 1:start + 1 + stride])
        for x in range(stride):
            a = row[x - 4] if x >= 4 else 0
            b = previous[x]
            c = previous[x - 4] if x >= 4 else 0
            if mode == 1:
                predictor = a
            elif mode == 2:
                predictor = b
            elif mode == 3:
                predictor = (a + b) // 2
            elif mode == 4:
                p = a + b - c
                distances = (abs(p - a), abs(p - b), abs(p - c))
                predictor = (a, b, c)[distances.index(min(distances))]
            else:
                assert mode == 0, mode
                predictor = 0
            row[x] = (row[x] + predictor) & 255
        rows.append(row)
        previous = row
    return width, height, rows, hashlib.sha256(raw).hexdigest()


def main():
    atlases = []
    for name, row_count in PEOPLE:
        path = ASSETS / f"{name}.png"
        width, height, pixels, sha = read_png(path)
        frames = []
        assert any(0 in row[3::4] for row in pixels), f"No transparent pixels: {name}"
        def cuts(occupied, count):
            result = [0]
            length = len(occupied)
            for part in range(1, count):
                nominal = part * length / count
                candidates = [i for i in range(int(nominal-length/count*.3),
                                               int(nominal+length/count*.3))
                              if not any(occupied[max(0,i-2):min(length,i+3)])]
                assert candidates, (name, part, 'no transparent separation')
                result.append(min(candidates, key=lambda i: abs(i-nominal)))
            return result + [length]
        row_cuts = cuts([any(a > 128 for a in row[3::4]) for row in pixels], row_count)
        columns = [cuts([any(pixels[y][x*4+3] > 128 for y in range(row_cuts[r], row_cuts[r+1]))
                         for x in range(width)], 4) for r in range(row_count)]
        for index in range(row_count * 4):
            col, row = index % 4, index // 4
            left, right = columns[row][col:col+2]
            top, bottom = row_cuts[row:row+2]
            points = [(x, y) for y in range(top, bottom) for x in range(left, right)
                      if pixels[y][x * 4 + 3] > 128]
            assert points, (name, index, "empty frame")
            x0, x1 = min(p[0] for p in points), max(p[0] for p in points) + 1
            y0, y1 = min(p[1] for p in points), max(p[1] for p in points) + 1
            # Hair/head center is stable when a sword, cloak or arm extends sideways.
            head = [x for x, y in points if y0 + (y1-y0)*.12 <= y <= y0 + (y1-y0)*.35]
            pivot_x = (min(head) + max(head) + 1) // 2
            assert left < x0 and x1 < right and top < y0 and y1 < bottom, (name, index, "clipped")
            frames.append([x0, y0, x1, y1, pivot_x, y1])
        atlases.append(dict(name=name, width=width, height=height, sha256=sha,
                           referenceHeight=frames[0][3]-frames[0][1], frames=frames))
        print(f"{name}: {width}x{height} RGBA, {len(frames)} nonempty unclipped frames")
    (ASSETS / "frames.json").write_text(json.dumps(atlases, indent=2) + "\n", encoding="utf-8")
    header = ['// Generated by tools/sprites/index_chapter3_atlases.py; PNG pixels are unchanged.',
              '#pragma once', '#include <array>', 'namespace Chapter3SpriteData', '{',
              'struct Frame { int left, top, right, bottom, pivotX, pivotY; };',
              'struct Atlas { const wchar_t* path; int width, height, count, referenceHeight; std::array<Frame, 20> frames; };',
              'inline constexpr std::array<Atlas, 6> atlases = {{']
    for a in atlases:
        header.append('{L"..\\\\Chapter3\\\\StateSheets-v2\\\\%s.png", %d, %d, %d, %d, {{' %
                      (a['name'], a['width'], a['height'], len(a['frames']), a['referenceHeight']))
        header += ['{' + ', '.join(map(str, f)) + '},' for f in a['frames']]
        header.append('}}},')
    header += ['}};', '}', '']
    (ROOT / 'SimpleGame/src/generated/Chapter3SpriteData.h').write_text('\n'.join(header), encoding='utf-8')
    # Preview uses the same bounds, fixed scale and pivots as the game renderer.
    (ASSETS / 'preview.html').write_text('''<!doctype html><meta charset="utf-8"><title>C03 NPC states</title>
<style>body{background:#15202a;color:#e1d4af;font:16px sans-serif;margin:24px}canvas{max-width:100%;height:auto;image-rendering:pixelated;border:1px solid #5a6972}button{margin:12px;padding:10px}</style>
<h1>C03 · NPC states</h1><button onclick="state='idle'">IDLE</button><button onclick="state='walk'">WALK</button><button onclick="state='attack'">ATTACK</button><button onclick="state='ranged'">RANGED</button><button onclick="paused=!paused">Pause</button><canvas width="1440" height="420"></canvas>
<p>Arms, equipment, alternating support legs and stable feet: compare against characters-v1.png. No frame-specific resizing.</p><script>
const data=DATA;let state='walk',paused=false,t=0,last=performance.now();const c=document.querySelector('canvas'),g=c.getContext('2d');g.imageSmoothingEnabled=false;
Promise.all(data.map(a=>new Promise(r=>{a.img=new Image;a.img.onload=r;a.img.src=a.name+'.png'}))).then(()=>requestAnimationFrame(draw));
function draw(now){if(!paused)t+=(now-last)/1000;last=now;g.fillStyle='#15202a';g.fillRect(0,0,c.width,c.height);data.forEach((a,i)=>{let n=state==='idle'?Math.floor(t*4)%4:state==='walk'?4+Math.floor(t*10)%8:state==='attack'?12+Math.floor(t*4)%4:16+Math.floor(t*4)%4;g.fillStyle='#e1d4af';g.fillText(a.name+' · '+state,30+i*240,35);if(n>=a.frames.length){g.fillText('no combat',30+i*240,70);return}let f=a.frames[n],s=200/a.referenceHeight;g.strokeStyle='#60717c';g.beginPath();g.moveTo(i*240,350);g.lineTo(i*240+230,350);g.stroke();g.drawImage(a.img,f[0],f[1],f[2]-f[0],f[3]-f[1],i*240+110-(f[4]-f[0])*s,350-(f[5]-f[1])*s,(f[2]-f[0])*s,(f[3]-f[1])*s);});requestAnimationFrame(draw)}
</script>'''.replace('DATA', json.dumps(atlases)), encoding='utf-8')
    width, height, pixels, sha = read_png(ASSETS / 'props.png')
    assert any(0 in row[3::4] for row in pixels), 'Props have no alpha transparency'
    props = []
    for i in range(8):
        left, right = (i % 4) * width // 4, (i % 4 + 1) * width // 4
        top, bottom = (i // 4) * height // 2, (i // 4 + 1) * height // 2
        points = [(x,y) for y in range(top,bottom) for x in range(left,right)
                  if pixels[y][x*4+3] > 128]
        box = [min(x for x,y in points), min(y for x,y in points),
               max(x for x,y in points)+1, max(y for x,y in points)+1]
        assert left < box[0] and box[2] < right and top < box[1] and box[3] < bottom, (i, 'props clipped')
        props.append(box)
    prop_header = ['// Generated alpha bounds; source PNG is unchanged.', '#pragma once', '#include <array>',
                   'namespace Chapter3PropData {',
                   'inline constexpr wchar_t path[] = L"..\\\\Chapter3\\\\StateSheets-v2\\\\props.png";',
                   f'inline constexpr int width = {width}, height = {height};',
                   'inline constexpr std::array<std::array<int, 4>, 8> frames = {{']
    prop_header += ['{{' + ', '.join(map(str, f)) + '}},' for f in props]
    prop_header += ['}};', '}', '']
    (ROOT/'SimpleGame/src/generated/Chapter3PropData.h').write_text('\n'.join(prop_header),encoding='utf-8')
    (ASSETS/'props.json').write_text(json.dumps(dict(width=width,height=height,sha256=sha,frames=props),indent=2)+'\n',encoding='utf-8')
    print(f'props: {width}x{height} RGBA, 8 nonempty unclipped cells')


if __name__ == '__main__':
    main()
