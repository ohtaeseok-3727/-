"""Build and verify navigation indexes for every game-project Markdown file."""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[2]
MARKER = "<!-- Generated by tools/docs/build_game_doc_index.py; edit source documents, then rerun. -->"
PREVIOUS_MARKER = "<!-- Generated by tools/build_game_doc_index.py; edit source documents, then rerun. -->"
EXCLUDED_DIRS = {".agents", ".git", ".vs", ".local_knowledge", "Debug", "Release", "x64"}
FOLDER_ROLES = {
    "docs": "기획·구현·설계·운영 문서",
    "tools": "프로젝트 지원 도구",
    "SimpleGame": "코드와 게임 자산 설명",
    "_game_resource_production": "게임 리소스·맵 제작 자료",
    "_story_finalization": "스토리 비교·검토·확정 자료",
    "_story_scene_production": "챕터별 장면 제작 단계와 최종본",
    "스토리 초안": "초안 자료",
    "스토리 적용 방안": "적용 방안 자료",
}


def markdown_files() -> list[Path]:
    return sorted(
        (path for path in ROOT.rglob("*.md")
         if not EXCLUDED_DIRS.intersection(path.relative_to(ROOT).parts)
         and path.name not in {"INDEX.md", "DOCS_INDEX.md"}),
        key=lambda path: path.relative_to(ROOT).as_posix().casefold(),
    )


def label(path: Path) -> str:
    try:
        with path.open(encoding="utf-8-sig") as source:
            for _ in range(40):
                line = source.readline()
                if not line:
                    break
                if re.match(r"^#{1,3} ", line):
                    return line.lstrip("# ").strip().replace("|", "\\|")[:110]
    except (OSError, UnicodeError):
        pass
    return path.stem.replace("|", "\\|")


def link(from_dir: Path, target: Path) -> str:
    relative = Path(os.path.relpath(target, from_dir)).as_posix()
    return quote(relative, safe="/-._~")


def rows(files: list[Path], from_dir: Path) -> list[str]:
    return [f"| [{label(path)}]({link(from_dir, path)}) | `{path.name}` |" for path in files]


def expected_indexes() -> tuple[dict[Path, str], int]:
    files = markdown_files()
    versioned = [path for path in files if path.relative_to(ROOT).parts[0] != "output"]
    output = [path for path in files if path.relative_to(ROOT).parts[0] == "output"]
    directories: set[Path] = set()
    for path in versioned:
        current = path.parent
        while current != ROOT:
            directories.add(current)
            current = current.parent

    indexes: dict[Path, str] = {}
    for directory in sorted(directories, key=lambda path: (len(path.parts), path.as_posix()), reverse=True):
        direct = [path for path in versioned if path.parent == directory]
        children = sorted((child for child in directories if child.parent == directory), key=lambda path: path.name.casefold())
        parent_index = ROOT / "DOCS_INDEX.md" if directory.parent == ROOT else directory.parent / "INDEX.md"
        parts = [MARKER, f"# {directory.name} 문서 인덱스", "",
                 f"[상위 문서 인덱스]({link(directory, parent_index)})", "",
                 "이 목록은 문서의 위치를 안내한다. 제목이나 폴더 이름만으로 사용자 확정 여부를 판단하지 않는다.", ""]
        if children:
            parts += ["## 하위 묶음", "", "| 묶음 | 위치 |", "| --- | --- |"]
            parts += [f"| {child.name} | [문서 목록]({link(directory, child / 'INDEX.md')}) |" for child in children]
            parts.append("")
        if direct:
            parts += ["## 이 폴더의 문서", "", "| 문서 제목 | 파일 |", "| --- | --- |"]
            parts += rows(direct, directory)
            parts.append("")
        indexes[directory / "INDEX.md"] = "\n".join(parts).rstrip() + "\n"

    root_direct = [path for path in versioned if path.parent == ROOT]
    top = sorted((directory for directory in directories if directory.parent == ROOT), key=lambda path: path.name.casefold())
    parts = [
        MARKER,
        "# 게임 프로젝트 문서 인덱스",
        "",
        "작업별 문서 위치를 찾는 진입점이다. 확정 설정과 미확정 제안은 각 본문의 표시를 따른다.",
        "게임 작업 규칙은 [AGENTS.md](AGENTS.md)와 상위 헌법에서 확인한다.",
        "",
        "## 먼저 읽을 경로",
        "",
        "| 작업 | 문서 |",
        "| --- | --- |",
        "| 게임 기획·설정 | [GAME_DESIGN.md](GAME_DESIGN.md)에서 주제를 고른다 |",
        "| 챕터 1 확정 스토리 | [CHAPTER_01_FINAL.md](_story_scene_production/05_final_chapters/CHAPTER_01_FINAL.md) |",
        "| 챕터 구현 현황 | [챕터 1 점검](docs/implementation/CHAPTER_01_IMPLEMENTATION_AUDIT.md), [챕터 2 구현](docs/implementation/CHAPTER_02_IMPLEMENTATION.md) |",
        "| 성능·구조 변경 | [PERFORMANCE_ANALYSIS.md](docs/performance/PERFORMANCE_ANALYSIS.md) |",
        "| 현재 작업 기록·함수 사전 | [프로젝트 로컬 인덱스](.agents/projects/INDEX.md) |",
        "| 과거 협업 기록 | [WORK_LOG.md](docs/process/WORK_LOG.md) |",
        "",
        "## 문서 묶음",
        "",
        "| 폴더 | 역할 | 문서 목록 |",
        "| --- | --- | --- |",
    ]
    parts += [
        f"| `{directory.name}` | {FOLDER_ROLES.get(directory.name, '프로젝트 문서')} | "
        f"[인덱스]({link(ROOT, directory / 'INDEX.md')}) |"
        for directory in top
    ]
    parts += ["", "## 루트 문서", "", "| 문서 제목 | 파일 |", "| --- | --- |"]
    parts += rows(root_direct, ROOT)
    parts.append("")
    if output:
        parts += [
            "## 로컬 미리보기 산출물",
            "",
            "`output/`은 Git 제외 경로다. 아래 문서는 현재 로컬 파일을 가리키며 다른 체크아웃에는 없을 수 있다.",
            "",
            "| 문서 제목 | 위치 |",
            "| --- | --- |",
        ]
        parts += [f"| [{label(path)}]({link(ROOT, path)}) | `{path.relative_to(ROOT).as_posix()}` |" for path in output]
        parts.append("")
    indexes[ROOT / "DOCS_INDEX.md"] = "\n".join(parts).rstrip() + "\n"
    return indexes, len(files)


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if an index is missing or stale")
    args = parser.parse_args()
    indexes, source_count = expected_indexes()
    stale = []
    for path, expected in indexes.items():
        if path.exists() and path.read_text(encoding="utf-8") == expected:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
            continue
        if path.exists() and not path.read_text(encoding="utf-8").startswith((MARKER, PREVIOUS_MARKER)):
            raise SystemExit(f"기존 수동 인덱스를 덮어쓰지 않습니다: {path}")
        path.write_text(expected, encoding="utf-8")
    if stale:
        raise SystemExit("누락되었거나 오래된 인덱스:\n" + "\n".join(stale))
    print(f"문서 {source_count}개, 계층 인덱스 {len(indexes)}개 확인")


if __name__ == "__main__":
    main()
