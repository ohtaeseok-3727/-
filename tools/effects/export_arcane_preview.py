"""Export the game's texture-free arcane shaders to its local WebGL2 preview."""
import json
import base64
import re
from pathlib import Path


class ArcanePreviewExporter:
    def export(self):
        root = Path(__file__).resolve().parents[2]
        source = (root / "SimpleGame/src/rendering/ArcaneEffectShaders.h").read_text(encoding="utf-8")
        shaders = {}
        for name in ("Vertex", "Fragment"):
            match = re.search(rf'{name}\s*=\s*R"GLSL\((.*?)\)GLSL"', source, re.S)
            if not match:
                raise ValueError(f"Missing {name} shader")
            shaders[name.lower()] = match.group(1).replace(
                "#version 330 core", "#version 300 es\nprecision highp float;\nprecision highp int;", 1
            )
        target = root / "output/mage-sword-song-v1/arcane-shaders.js"
        target.write_text("// Generated by tools/effects/export_arcane_preview.py.\n"
                          "window.ArcaneShaders = " + json.dumps(shaders) + ";\n", encoding="utf-8")
        # Preserve the existing character image byte-for-byte. A data URL keeps local-file
        # Canvas uploads origin-clean, so the preview does not need an HTTP server.
        character = root / "SimpleGame/Assets/Characters/SmallMage/mana-blade-motion-v1.png"
        data = base64.b64encode(character.read_bytes()).decode("ascii")
        target.with_name("character-data.js").write_text(
            "// Existing character asset, embedded for local-file preview.\n"
            'window.ArcaneCharacterImage = "data:image/png;base64,' + data + '";\n', encoding="utf-8"
        )
        print("Exported shared OpenGL effect shaders to WebGL2 preview")


if __name__ == "__main__":
    ArcanePreviewExporter().export()
